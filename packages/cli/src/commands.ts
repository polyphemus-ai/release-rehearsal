// Every command, declared once. The usage text, `poly help`, and `poly capabilities` are all
// generated from this list, so they can't drift apart (docs/design/cli-for-agents.md §1).

export interface CommandSpec {
  /** Stable id for agents and docs, e.g. "sessions.show". */
  id: string;
  usage: string;
  summary: string;
  /** read: changes nothing · write: changes polyphemus state · destructive: removes something · interactive: needs a person at a terminal */
  effects: 'read' | 'write' | 'destructive' | 'interactive';
  /** Prints the JSON envelope with --json, or when stdout isn't a terminal. */
  json: boolean;
  examples: string[];
  /** Arguments, in order (positional unless `flag`): these become the MCP tool's input schema. */
  params?: Array<{ name: string; type: 'string' | 'number'; description: string; required?: boolean; flag?: string }>;
}

