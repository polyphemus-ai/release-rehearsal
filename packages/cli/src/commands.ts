/** The usage text for `polyphemus --help` and `poly help`. */
export function usageText(): string {
  const lines = COMMANDS.map(({ usage, summary }) => (usage.length <= 26 ? `  ${usage.padEnd(27)} ${summary}` : `  ${usage}\n  ${' '.repeat(28)}${summary}`));
  return `Usage:\n${lines.join('\n')}\n\nAgents and scripts: every list and show command prints JSON with --json (or when piped). Start with: poly capabilities`;
}

/** A command by id ("sessions.show") or words ("sessions show"). */
export function findCommand(name: string): CommandSpec | undefined {
  const id = name.trim().replace(/\s+/g, '.');
  return COMMANDS.find((command) => command.id === id);
}
